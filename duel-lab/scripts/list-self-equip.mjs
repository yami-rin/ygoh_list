#!/usr/bin/env node
// Lists the cards that have an effect that equips the card itself "as an Equip Card" / "as an Equip Spell"
// (Hero of Hope ② searches "a card with an effect that equips itself as an Equip Card").
//
// Sources: data/cards.json (Duel Lab), custom/*.json (original cards) and, when present, the Japanese card
// databases of the MDPro3 client (Data/locales/ja-JP/cards.cdb, Expansions/latest-ja.cdb).
// A card is listed when
//   - it is a Union monster (TYPE_UNION: "equip this card to ... as an Equip Card" in the Union rules), or
//   - a sentence of its text makes this card / this monster / itself (このカード / このモンスター / 自身) the object
//     of "装備カード扱い" or "装備魔法カード扱い" ("... このカードを ... 装備カード扱いとして ... に装備する").
// Cards that only equip other cards ("そのモンスターを装備カード扱いとしてこのカードに装備する"), that only refer to
// being equipped ("このカードが装備カード扱いとして装備されている場合") and Extra Deck monsters (they cannot be in
// the Deck) are not listed.
//
// Usage: node scripts/list-self-equip.mjs            print the summary and the boundary cases
//        node scripts/list-self-equip.mjs --write    also rewrite the code list in custom/scripts/c77700810.lua
//        node scripts/list-self-equip.mjs --json     print the listed cards as JSON
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DatabaseSync} from 'node:sqlite';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TYPE_UNION = 0x400;
const EXTRA = 0x40 | 0x2000 | 0x800000 | 0x4000000; // Fusion, Synchro, Xyz, Link
const TARGET = path.join(ROOT, 'custom', 'scripts', 'c77700810.lua');
const BEGIN = '--BEGIN SELF_EQUIP (generated by scripts/list-self-equip.mjs --write)';
const END = '--END SELF_EQUIP';

const AS_EQUIP = /装備(?:魔法)?カード扱い/;
// このカードを / このモンスターを / 自身を (or は) ... 装備カード扱い, with no other object ("を", except "～を持つ")
// in between; also "このカードと～をそれぞれ～装備カード扱い" (equips itself together with another card) and
// "墓地へ送らずに装備カード扱いとして" (the destroyed card itself, e.g. Dragunity Javelin)
const SELF_EQUIP = new RegExp([
  /(?:このカード|このモンスター|自身)(?:を|は)(?:[^。を]|を持つ)*?装備(?:魔法)?カード扱い/.source,
  /このカードと[^。を]*?をそれぞれ[^。を]*?装備(?:魔法)?カード扱い/.source,
  /墓地へ送らずに装備(?:魔法)?カード扱い/.source,
].join('|'));

function loadCards() {
  const cards = new Map(); // code -> {code, name, type, texts:Set, sources:Set}
  const add = (code, name, type, text, source) => {
    if (!code || !text) return;
    let c = cards.get(code);
    if (!c) cards.set(code, c = {code, name, type, texts: new Set(), sources: new Set()});
    c.texts.add(text);
    c.sources.add(source);
  };
  const lab = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'cards.json'), 'utf8'));
  for (const c of Object.values(lab)) if (!c.alias) add(c.code, c.name, c.type, c.text, 'duel-lab');
  for (const f of fs.readdirSync(path.join(ROOT, 'custom')).filter(f => f.endsWith('.json')).sort()) {
    for (const c of JSON.parse(fs.readFileSync(path.join(ROOT, 'custom', f), 'utf8')).cards) add(c.code, c.name, c.type, c.text, 'custom');
  }
  const client = path.join(ROOT, 'runtime', 'MDPro3-client');
  for (const db of [path.join(client, 'Data', 'locales', 'ja-JP', 'cards.cdb'), path.join(client, 'Expansions', 'latest-ja.cdb')]) {
    if (!fs.existsSync(db)) continue;
    const d = new DatabaseSync(db, {readOnly: true});
    for (const r of d.prepare('select d.id, d.alias, d.type, t.name, t.desc from datas d join texts t on t.id = d.id').all()) {
      if (!r.alias) add(Number(r.id), r.name, Number(r.type), r.desc, 'mdpro3');
    }
    d.close();
  }
  return cards;
}

function classify(card) {
  const sentences = [...card.texts].flatMap(t => t.split(/(?<=。)/)).filter(s => AS_EQUIP.test(s));
  // "自身を装備カード扱いで装備する効果を持つカード" describes other cards (Hero of Hope ② itself)
  const hit = sentences.find(s => SELF_EQUIP.test(s) && !/装備する効果を持つカード/.test(s));
  if (card.type & TYPE_UNION) return {listed: !(card.type & EXTRA), reason: 'union', sentence: hit || sentences[0] || ''};
  if (hit) return {listed: !(card.type & EXTRA), reason: card.type & EXTRA ? 'extra' : 'text', sentence: hit};
  // boundary: the text mentions this card and "as an Equip Card" in one sentence but this card is not what is equipped
  const near = sentences.find(s => /このカード|このモンスター|自身/.test(s));
  return {listed: false, reason: near ? 'boundary' : 'other', sentence: near || sentences[0] || ''};
}

const cards = loadCards();
const rows = [...cards.values()].map(c => ({...c, ...classify(c)}));
const listed = rows.filter(r => r.listed).sort((a, b) => a.code - b.code);
const args = new Set(process.argv.slice(2));

if (args.has('--json')) {
  console.log(JSON.stringify(listed.map(r => ({code: r.code, name: r.name, reason: r.reason, sentence: r.sentence})), null, 1));
} else {
  const count = k => rows.filter(r => r.reason === k).length;
  console.log(`listed: ${listed.length} (union ${listed.filter(r => r.reason === 'union').length}, text ${listed.filter(r => r.reason === 'text').length})`);
  console.log(`not listed: Extra Deck self-equip ${count('extra')}, boundary ${count('boundary')}`);
  if (args.has('--verbose')) {
    for (const r of listed) console.log(`+ ${r.code}\t${r.reason}\t${r.name}\t${r.sentence.trim()}`);
    for (const r of rows.filter(r => r.reason === 'extra' || r.reason === 'boundary')) console.log(`- ${r.code}\t${r.reason}\t${r.name}\t${r.sentence.trim()}`);
  }
}

if (args.has('--write')) {
  const lua = fs.readFileSync(TARGET, 'utf8');
  const nl = lua.includes('\r\n') ? '\r\n' : '\n';
  const i = lua.indexOf(BEGIN), j = lua.indexOf(END);
  if (i < 0 || j < i) throw new Error(`markers not found in ${TARGET}`);
  const codes = listed.map(r => r.code);
  const lines = [];
  for (let k = 0; k < codes.length; k += 10) lines.push('\t' + codes.slice(k, k + 10).join(',') + ',');
  const block = [BEGIN, `--${codes.length} cards`, 'local SELF_EQUIP={', ...lines, '}'].join(nl) + nl;
  fs.writeFileSync(TARGET, lua.slice(0, i) + block + lua.slice(j));
  console.log(`wrote ${codes.length} codes into ${path.relative(ROOT, TARGET)}`);
}
